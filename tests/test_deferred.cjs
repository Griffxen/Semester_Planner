const assert = require('node:assert/strict');
const D = require('../static/deferred.js');
const U = require('../static/mobile/domain.js');
const reference = {date:'2026-10-01',end_date:'2026-10-02',start_time:'09:00',end_time:'10:00',due:'2026-10-03T12:00',milestones:[{label:'原节点',stop_at:'2026-10-02T11:00+08:00',done:true}]};
const first = {id:'a',title:'<资料整理>',category:'科研',notes:'等资料',deferred:true,deferred_at:'2026-10-18T12:00:00+00:00',previous_schedule:reference};
const second = {...first,id:'b',title:'另一任务',category:'个人',deferred_at:'2026-10-19T12:00:00+00:00'};
const data = {tasks:[],deferred_tasks:[first,second],course_dates:[]};
assert.deepEqual(D.filtered(data).map(t=>t.id),['b','a']);
assert.deepEqual(D.filtered(data,{category:'科研',query:'原节点'}).map(t=>t.id),['a']);
assert.equal(D.filtered(data,{query:'不存在'}).length,0);
const blank = D.blank(first);
assert.equal(blank.deferred,false);
for (const field of ['date','end_date','start_time','end_time','due']) assert.equal(blank[field],'');
assert.deepEqual(blank.milestones,[]);
blank.previous_schedule.milestones[0].label = '草稿修改';
assert.equal(reference.milestones[0].label,'原节点','reschedule drafts must not mutate reference data');
const markup = D.list(D.filtered(data));
assert(markup.includes('&lt;资料整理&gt;'));
assert(!markup.includes('2026-10-01'),'list must not display historical times');
assert(D.reference(first).includes('已完成'));
assert(D.reference(first).includes('2026-10-03 12:00'));
assert(D.reference({}).includes('没有原安排'));
const filters = {category:'',query:'',hideDone:false,showCourses:true};
assert.deepEqual(U.dayEntries(data,'2026-10-01',filters),{timed:[],dated:[],ongoing:[],courses:[],nodes:[]});
assert.deepEqual(U.workloadCounts(data,'2026-10-02',filters),{slots:0,dated:0,points:0,untimed:0});
assert.deepEqual(U.busyIntervals(data,'2026-10-01',filters),[]);
const archive = D.backup(data);
assert.equal(archive.format,1);
assert.deepEqual(archive.tasks,[first,second]);
assert.deepEqual(archive.tasks[0].previous_schedule,reference);
assert.equal(data.tasks.length,0,'complete backup must not change live schedule data');
console.log('Deferred list, reference isolation, blank drafts and schedule exclusion passed');
